#!/usr/bin/env python3
# 让 build/soong 下 v1.3 时代生成的 *_pb.go 能在 google.golang.org/protobuf v1.36 上编译。
#
# 思路：
#   1) external/golang-protobuf/proto/compat_legacy.go 里补上"纯函数"式旧符号
#      （RegisterType/RegisterEnum/RegisterFile/EnumName/UnmarshalJSONEnum/
#        ProtoPackageIsVersion3 以及 proto.String/Bool/Int../.. 指针辅助函数）。
#      注意：该文件绝不能 import protoadapt/protoimpl/prototext，否则 microfactory
#      静态扫依赖发现 proto -> prototext -> proto 成环，bootstrap 死锁。
#   2) 每个 *_pb.go 所在包里新增一个辅助文件，实现需要 v1->v2 转换的
#      InternalMessageInfo（proto.Marshal/Unmarshal/Size/Merge/DiscardUnknown）
#      与 CompactTextString；再把 pb.go 里的 `var xxx_messageInfo_X proto.InternalMessageInfo`
#      和 `return proto.CompactTextString(m)` 指向本地实现。
import os
import re
import sys

SRC = '/home/luge/wahoo/twrp/src'
PB_DIRS = [
    'build/soong/cmd/extract_apks/bundle_proto',
    'build/soong/cmd/sbox/sbox_proto',
    'build/soong/ui/metrics/metrics_proto',
    'build/soong/ui/metrics/upload_proto',
    'build/soong/ui/status/build_error_proto',
    'build/soong/ui/status/build_progress_proto',
    'build/soong/ui/status/ninja_frontend',
]

