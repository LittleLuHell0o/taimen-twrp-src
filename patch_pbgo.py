VAR_RE = re.compile(r'^var (xxx_messageInfo_\w+) proto\.InternalMessageInfo$')


def patch_pb_dir(d):
    full = os.path.join(SRC, d)
    pkg = None
    pb_files = []
    for name in sorted(os.listdir(full)):
        if not name.endswith('.pb.go'):
            continue
        path = os.path.join(full, name)
        with open(path, encoding='utf-8') as f:
            for line in f:
                if line.startswith('package '):
                    pkg = line.split()[1].strip()
                    break
        pb_files.append(path)
    if pkg is None:
        print('SKIP %s: no package' % d)
        return
    helper_path = os.path.join(full, 'legacy_proto_support.go')
    if not os.path.exists(helper_path):
        with open(helper_path, 'w', encoding='utf-8') as f:
            f.write(HELPER % {'pkg': pkg})
    n_var = n_ctext = 0
    for path in pb_files:
        with open(path, encoding='utf-8') as f:
            lines = f.readlines()
        out = []
        for line in lines:
            if VAR_RE.match(line.strip()):
                out.append('var %s = &internalMessageInfo{}\n' % VAR_RE.match(line.strip()).group(1))
                n_var += 1
            elif 'proto.CompactTextString(' in line:
                out.append(line.replace('proto.CompactTextString(', 'legacyCompactText('))
                n_ctext += 1
            else:
                out.append(line)
        with open(path, 'w', encoding='utf-8') as f:
            f.writelines(out)
    print('OK   %-52s pkg=%-32s vars=%d compactText=%d' % (d, pkg, n_var, n_ctext))


def main():
    for d in PB_DIRS:
        patch_pb_dir(d)

    # rule_builder.go: MarshalTextString / UnmarshalText
    p = os.path.join(SRC, 'build/soong/android/rule_builder.go')
    with open(p, encoding='utf-8') as f:
        txt = f.read()
    if 'legacyMarshalText' in txt:
        print('SKIP rule_builder.go already patched')
    else:
        txt = txt.replace('proto.MarshalTextString(&manifest)', 'legacyMarshalText(&manifest)')
        txt = txt.replace('err := proto.UnmarshalText(content, &manifest)',
                          'err := prototext.Unmarshal([]byte(content), protoadapt.MessageV2Of(&manifest))')
        txt = txt.replace('\t"github.com/golang/protobuf/proto"\n',
                          '\t"github.com/golang/protobuf/proto"\n\t"google.golang.org/protobuf/encoding/prototext"\n\t"google.golang.org/protobuf/protoadapt"\n')
        with open(p, 'w', encoding='utf-8') as f:
            f.write(txt)
        helper = os.path.join(SRC, 'build/soong/android/legacy_proto_support.go')
        with open(helper, 'w', encoding='utf-8') as f:
            f.write(HELPER % {'pkg': 'android'} +
                    '\n// legacyMarshalText renders m as a (multi-line) proto text.\n'
                    'func legacyMarshalText(m protoadapt.MessageV1) string {\n'
                    '\tb, err := prototext.MarshalOptions{Multiline: true}.Marshal(protoadapt.MessageV2Of(m))\n'
                    '\tif err != nil {\n\t\treturn ""\n\t}\n\treturn string(b)\n}\n')
        print('OK   rule_builder.go patched')

    # sbox.go: UnmarshalText
    p = os.path.join(SRC, 'build/soong/cmd/sbox/sbox.go')
    with open(p, encoding='utf-8') as f:
        txt = f.read()
    if 'prototext.Unmarshal' in txt:
        print('SKIP sbox.go already patched')
    else:
        txt = txt.replace('proto.UnmarshalText(string(manifestData), &manifest)',
                          'prototext.Unmarshal(manifestData, protoadapt.MessageV2Of(&manifest))')
        txt = txt.replace('\t"google/golang/protobuf/proto"\n',
                          '\t"google/golang/protobuf/proto"\n\t"google.golang.org/protobuf/encoding/prototext"\n\t"google.golang.org/protobuf/protoadapt"\n')
        with open(p, 'w', encoding='utf-8') as f:
            f.write(txt)
        print('OK   sbox.go patched')


if __name__ == '__main__':
    main()
